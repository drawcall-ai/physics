import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const source = new URL(import.meta.resolve("@mujoco/mujoco"));
const output = new URL("../generated/", import.meta.url);
const [javascript, wasm, metadata] = await Promise.all([
  readFile(source, "utf8"),
  readFile(new URL("mujoco.wasm", source)),
  readFile(new URL("package.json", source), "utf8"),
]);
const version = JSON.parse(metadata).version;
const licenseURL = `https://raw.githubusercontent.com/google-deepmind/mujoco/${version}/LICENSE`;
const licenseHash =
  "cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30";
const cache = new URL("../.cache/", import.meta.url);
const licenseFile = new URL(`mujoco-${version}-LICENSE`, cache);
const license = await readFile(licenseFile).catch(async (error) => {
  if (error.code !== "ENOENT") throw error;
  const response = await fetch(licenseURL);
  if (!response.ok)
    throw new Error(`MuJoCo license download failed: ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
});
if (createHash("sha256").update(license).digest("hex") !== licenseHash)
  throw new Error("MuJoCo license checksum mismatch");
const asset = "new URL('mujoco.wasm', import.meta.url).href";
if (javascript.split(asset).length !== 2)
  throw new Error(
    "Expected exactly one MuJoCo WASM asset URL; review the upstream loader",
  );

await mkdir(output, { recursive: true });
await mkdir(cache, { recursive: true });
await Promise.all([
  writeFile(licenseFile, license),
  // wasmBinary supplies the bytes. A literal URL would emit a second, unused WASM asset in Vite.
  writeFile(
    new URL("mujoco.js", output),
    javascript.replace(asset, "'mujoco.wasm'"),
  ),
  writeFile(
    new URL("wasm.js", output),
    `export default ${JSON.stringify(wasm.toString("base64"))};\n`,
  ),
  writeFile(
    new URL("mujoco.d.ts", output),
    'export { default } from "@mujoco/mujoco";\n',
  ),
  writeFile(
    new URL("wasm.d.ts", output),
    "declare const base64: string;\nexport default base64;\n",
  ),
  writeFile(new URL("LICENSE", output), license),
  writeFile(
    new URL("NOTICE", output),
    [
      `MuJoCo ${version}: https://github.com/google-deepmind/mujoco/tree/${version}`,
      "Copyright Google DeepMind. Licensed under Apache-2.0; see LICENSE.",
      `License source: ${licenseURL} (SHA-256 ${licenseHash}).`,
      "Generated by @drawcall/physics-mujoco/scripts/embed.mjs from @mujoco/mujoco.",
      "mujoco.js replaces the default WASM asset URL with a plain filename; wasm.js embeds the unmodified binary.",
      "",
    ].join("\n"),
  ),
]);
